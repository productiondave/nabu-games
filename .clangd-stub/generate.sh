#!/bin/sh
# Regenerates clangd-friendly copies of NABU-LIB headers.
# Re-run whenever you update NABU-LIB.  Usage: ./generate.sh [/path/to/NABULIB]
#
# clangd can't parse SDCC's `__sfr __at 0xNN NAME;`, and the .h files #include their
# own .c implementation (which contains bare __asm/__endasm blocks).  So we emit a patched
# header copy and an EMPTY .c next to it (quoted includes search the including file's dir first).
set -e
SRC=${1:-$HOME/dev/z80/NABU-LIB/NABULIB}
DST=$(cd "$(dirname "$0")" && pwd)
for f in NABU-LIB NabuTracker RetroNET-FileStore; do
  sed -E 's/^__sfr[[:space:]]+__at[[:space:]]+0x[0-9A-Fa-f]+[[:space:]]+([A-Za-z_0-9]+);/volatile unsigned char \1;/' \
    "$SRC/$f.h" > "$DST/$f.h"
  # Stub .c: prototypes only (some functions, e.g. vdp_refreshViewPort, are defined in the .c
  # without a prototype in the .h).  Redundant prototypes are harmless in C.
  {
    echo "// generated by generate.sh - prototypes only"
    sed -nE 's/^[[:space:]]*((inline|static)[[:space:]]+)?(void|bool|u?int(8|16|32)_t|int|char|unsigned [a-z]+)[[:space:]]+\**([A-Za-z_][A-Za-z_0-9]*)[[:space:]]*\(([^)]*)\)[[:space:]]*(__z88dk_fastcall)?[[:space:]]*\{.*/\1\3 \5(\6);/p' "$SRC/$f.c" \
      | grep -vE '^(if|while|for|switch|else|return)\b'
  } > "$DST/$f.c"
done
echo "generated stubs in $DST from $SRC"
